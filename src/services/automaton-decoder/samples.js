const UNIT_TYPES = ['UNIDAD', 'PELOTÓN', 'LEGIÓN', 'ESCUADRA', 'NODO', 'DIVISIÓN']
const LETTERS = 'ABCDEFGHJKLMNPRSTVXZ'

const pick = (list) => list[Math.floor(Math.random() * list.length)]
const int = (min, max) => min + Math.floor(Math.random() * (max - min + 1))

const unitId = () => `${int(1, 99)}-${pick(LETTERS)}${Math.random() < 0.4 ? pick(LETTERS) : ''}`
const unit = () => `${pick(UNIT_TYPES)} ${unitId()}`
const coords = () => `${(Math.random() * 180 - 90).toFixed(1)} / ${(Math.random() * 360 - 180).toFixed(1)}`

let lastTemplate = -1

export function randomTransmission() {
  let index
  do index = Math.floor(Math.random() * TEMPLATES.length)
  while (index === lastTemplate && TEMPLATES.length > 1)
  lastTemplate = index

  const template = TEMPLATES[index]
  const planet = template.text.includes('{PLANET}') || Math.random() < 0.7 ? pick(PLANETS) : null
  const text = template.text
    .replaceAll('{UNIT}', unit)
    .replaceAll('{ID}', unitId)
    .replaceAll('{N}', () => String(int(2, 999)))
    .replaceAll('{C}', () => String(int(1, 9)))
    .replaceAll('{PLANET}', planet?.toUpperCase() ?? '')

  return {
    faction: 'automaton',
    propaganda: template.propaganda,
    origin: [pick(SOURCES), planet ?? `Coordenadas ${coords()}`].join(' · '),
    text,
  }
}
